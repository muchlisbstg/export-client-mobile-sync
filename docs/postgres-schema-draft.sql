-- Inventory ledger controls.
CREATE FUNCTION app_private.guard_inventory_entry_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE movement_status text;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'inventory_entries_are_append_only';
  END IF;
  SELECT status INTO movement_status
  FROM app_private.inventory_movements
  WHERE tenant_id=NEW.tenant_id AND id=NEW.movement_id;
  IF movement_status IS DISTINCT FROM 'draft' THEN
    RAISE EXCEPTION 'inventory_movement_not_draft';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER inventory_entries_guard
  BEFORE INSERT OR UPDATE OR DELETE ON app_private.inventory_entries
  FOR EACH ROW EXECUTE FUNCTION app_private.guard_inventory_entry_mutation();

CREATE FUNCTION app_private.guard_inventory_movement_update()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE resulting_balance bigint;
DECLARE movement_entry record;
BEGIN
  IF OLD.status='posted' AND (
    NEW.tenant_id IS DISTINCT FROM OLD.tenant_id OR
    NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key OR
    NEW.payload_hash IS DISTINCT FROM OLD.payload_hash OR
    NEW.movement_type IS DISTINCT FROM OLD.movement_type OR
    NEW.occurred_at IS DISTINCT FROM OLD.occurred_at OR
    NEW.recorded_by IS DISTINCT FROM OLD.recorded_by OR
    NEW.reference_type IS DISTINCT FROM OLD.reference_type OR
    NEW.reference_id IS DISTINCT FROM OLD.reference_id OR
    NEW.created_at IS DISTINCT FROM OLD.created_at OR
    NEW.status IS DISTINCT FROM OLD.status
  ) THEN
    RAISE EXCEPTION 'posted_inventory_movement_is_immutable';
  END IF;

  IF OLD.status='draft' AND NEW.status='posted' THEN
    IF NOT EXISTS (
      SELECT 1 FROM app_private.inventory_entries
      WHERE tenant_id=NEW.tenant_id AND movement_id=NEW.id
    ) THEN RAISE EXCEPTION 'empty_movement'; END IF;

    FOR movement_entry IN
      SELECT lot_id,site_id,SUM(quantity_milli_delta) AS delta
      FROM app_private.inventory_entries
      WHERE tenant_id=NEW.tenant_id AND movement_id=NEW.id
      GROUP BY lot_id,site_id
    LOOP
      SELECT COALESCE(SUM(e.quantity_milli_delta),0) INTO resulting_balance
      FROM app_private.inventory_entries e
      JOIN app_private.inventory_movements m
        ON m.tenant_id=e.tenant_id AND m.id=e.movement_id
      WHERE e.tenant_id=NEW.tenant_id
        AND e.lot_id=movement_entry.lot_id
        AND e.site_id=movement_entry.site_id
        AND m.status='posted';
      IF resulting_balance + movement_entry.delta < 0 THEN
        RAISE EXCEPTION 'insufficient_stock';
      END IF;
    END LOOP;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER inventory_movement_guard
  BEFORE UPDATE ON app_private.inventory_movements
  FOR EACH ROW EXECUTE FUNCTION app_private.guard_inventory_movement_update();

